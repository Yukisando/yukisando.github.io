// Builds the two static ColdSnap pages from one template:
//   tools/coldsnap-site/index.html  ->  coldsnap/index.html (French, served at /)
//                                   ->  coldsnap/en/index.html (English, served at /en/)
// The template carries the English text plus data-i18n keys; French comes from
// coldsnap/js/i18n-strings.js, the same file the browser uses for script-made text.
// Run after editing the template or the strings:  node tools/coldsnap-build.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const template = readFileSync(join(root, 'tools/coldsnap-site/index.html'), 'utf8');
const sandbox = { window: {} };
vm.runInNewContext(readFileSync(join(root, 'coldsnap/js/i18n-strings.js'), 'utf8'), sandbox);
const { FR, TITLES } = sandbox.window.CS_STRINGS;

const escapeAttr = s => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const escapeText = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');

const PAGES = {
  fr: {
    out: 'coldsnap/index.html',
    url: 'https://coldsnap.fr/',
    ogLocale: 'fr_FR', ogLocaleAlt: 'en_GB',
    description: FR['meta.description'],
    ogDescription: FR['meta.ogDescription'],
  },
  en: {
    out: 'coldsnap/en/index.html',
    url: 'https://coldsnap.fr/en/',
    ogLocale: 'en_GB', ogLocaleAlt: 'fr_FR',
    description: 'Gamification studio in France and Switzerland: interactive museum installations, educational games and cross-platform apps.',
    ogDescription: 'Interactive installations, educational games and cross-platform apps. France & Switzerland.',
  },
};

const missing = new Set();
function translate(html) {
  const fr = key => {
    if (key in FR) return FR[key];
    missing.add(key);
    return null;
  };
  // <tag data-i18n="key">text</tag> and <tag data-i18n-html="key">markup</tag> (leaf elements)
  html = html.replace(/(<([a-z0-9]+)\b[^>]*\sdata-i18n(-html)?="([^"]+)"[^>]*>)([\s\S]*?)(<\/\2>)/g,
    (all, open, tag, isHtml, key, inner, close) => {
      const value = fr(key);
      return value === null ? all : open + (isHtml ? value : escapeText(value)) + close;
    });
  // data-i18n-attr="attr:key, attr2:key2"
  html = html.replace(/<[a-z0-9]+\b[^>]*\sdata-i18n-attr="([^"]+)"[^>]*>/g, (tag, spec) => {
    for (const pair of spec.split(',')) {
      const [attr, key] = pair.split(':').map(s => s.trim());
      const value = fr(key);
      if (value !== null) tag = tag.replace(new RegExp(`(\s${attr}=")[^"]*"`), `$1${escapeAttr(value)}"`);
    }
    return tag;
  });
  // legal pages on nathandecastro.com take ?lang=fr
  html = html.replace(/(data-legal-href="([^"]+)"[^>]*?\shref=")[^"]*"/g, '$1$2?lang=fr"');
  return html;
}

for (const [lang, page] of Object.entries(PAGES)) {
  let html = template
    .replaceAll('{{banner}}', 'Generated by tools/coldsnap-build.mjs from tools/coldsnap-site/index.html. Do not edit by hand.')
    .replaceAll('{{lang}}', lang)
    .replaceAll('{{title}}', escapeAttr(TITLES[lang]))
    .replaceAll('{{description}}', escapeAttr(page.description))
    .replaceAll('{{og_description}}', escapeAttr(page.ogDescription))
    .replaceAll('{{og_locale}}', page.ogLocale)
    .replaceAll('{{og_locale_alt}}', page.ogLocaleAlt)
    .replaceAll('{{url}}', page.url)
    .replaceAll('{{current_fr}}', lang === 'fr' ? ' aria-current="page"' : '')
    .replaceAll('{{current_en}}', lang === 'en' ? ' aria-current="page"' : '');
  if (lang === 'fr') html = translate(html);
  const leftover = html.match(/\{\{[a-z_]+\}\}/);
  if (leftover) throw new Error(`Unfilled placeholder ${leftover[0]} in ${page.out}`);
  mkdirSync(dirname(join(root, page.out)), { recursive: true });
  writeFileSync(join(root, page.out), html);
  console.log(`${page.out}  ${(Buffer.byteLength(html) / 1024).toFixed(1)} KB`);
}
if (missing.size) console.warn(`No French for: ${[...missing].join(', ')}`);
